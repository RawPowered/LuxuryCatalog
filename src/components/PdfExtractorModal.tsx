import React, { useState, useRef } from 'react';
import { XCircle, Upload, Loader2, CheckCircle2, Trash2 } from 'lucide-react';
import { extractDoorsFromPdf, ExtractedDoor } from '../lib/pdfExtractor';

interface PdfExtractorModalProps {
  isOpen: boolean;
  onClose: () => void;
  onRestore: (doors: ExtractedDoor[]) => void;
}

export const PdfExtractorModal: React.FC<PdfExtractorModalProps> = ({ isOpen, onClose, onRestore }) => {
  const [isExtracting, setIsExtracting] = useState(false);
  const [progress, setProgress] = useState(0);
  const [status, setStatus] = useState('');
  const [extractedDoors, setExtractedDoors] = useState<ExtractedDoor[]>([]);
  const fileInputRef = useRef<HTMLInputElement>(null);

  if (!isOpen) return null;

  const handleFileUpload = async (e: React.ChangeEvent<HTMLInputElement>) => {
    const file = e.target.files?.[0];
    if (!file) return;

    setIsExtracting(true);
    setProgress(0);
    setStatus('Reading PDF...');
    setExtractedDoors([]);

    try {
      const doors = await extractDoorsFromPdf(file, (p, s) => {
        setProgress(p);
        setStatus(s);
      });
      
      setExtractedDoors(doors);
      setStatus(`Successfully extracted ${doors.length} doors.`);
    } catch (error: any) {
      console.error("Extraction error:", error);
      setStatus(`Error: ${error.message || 'Failed to extract doors'}`);
    } finally {
      setIsExtracting(false);
    }
  };

  const handleRestore = () => {
    // Sanitize SKUs before restoring
    const sanitizedDoors = extractedDoors.map(door => ({
      ...door,
      sku: door.sku.replace(/[^a-zA-Z0-9-]/g, '').trim() // Basic sanitation: only alphanumeric and dashes
    }));
    onRestore(sanitizedDoors);
    onClose();
  };

  return (
    <div className="fixed inset-0 z-50 flex items-center justify-center bg-black/50 backdrop-blur-sm p-4">
      <div className="bg-white rounded-2xl shadow-xl max-w-4xl w-full p-6 animate-in fade-in zoom-in duration-200 max-h-[90vh] flex flex-col">
        <div className="flex justify-between items-center mb-6 shrink-0">
          <h3 className="text-xl font-semibold text-gray-900">Restore from PDF Catalog</h3>
          {!isExtracting && (
            <button onClick={onClose} className="text-gray-400 hover:text-gray-600 transition-colors">
              <XCircle className="w-6 h-6" />
            </button>
          )}
        </div>

        <div className="space-y-6 overflow-hidden flex flex-col flex-1">
          <div className="bg-blue-50 border border-blue-100 rounded-xl p-4 text-sm text-blue-800 shrink-0">
            <p>Upload a previously generated PDF catalog to extract and restore the doors back into your queue. This process may take a few moments for large catalogs.</p>
          </div>

          {!isExtracting && extractedDoors.length === 0 && (
            <div 
              className="border-2 border-dashed border-gray-300 rounded-xl p-12 flex flex-col items-center justify-center cursor-pointer hover:bg-gray-50 hover:border-indigo-300 transition-all flex-1"
              onClick={() => fileInputRef.current?.click()}
            >
              <Upload className="w-12 h-12 text-gray-400 mb-4" />
              <p className="text-lg font-medium text-gray-700">Click to upload PDF Catalog</p>
              <p className="text-sm text-gray-500 mt-2">Only use PDFs generated by this application</p>
              <input 
                type="file" 
                ref={fileInputRef} 
                onChange={handleFileUpload} 
                accept="application/pdf" 
                className="hidden" 
              />
            </div>
          )}

          {isExtracting && (
            <div className="py-12 flex flex-col items-center justify-center flex-1">
              <Loader2 className="w-12 h-12 text-indigo-600 animate-spin mb-4" />
              <p className="text-lg font-medium text-gray-900">{status}</p>
              <div className="w-full max-w-md bg-gray-200 rounded-full h-2.5 mt-4">
                <div className="bg-indigo-600 h-2.5 rounded-full transition-all duration-300" style={{ width: `${progress}%` }}></div>
              </div>
            </div>
          )}

          {!isExtracting && extractedDoors.length > 0 && (
            <div className="flex flex-col flex-1 overflow-hidden">
              <div className="flex items-center justify-center space-x-3 text-emerald-600 shrink-0 mb-4">
                <CheckCircle2 className="w-8 h-8" />
                <span className="text-xl font-semibold">Extraction Complete</span>
              </div>
              
              <p className="text-center text-gray-600 shrink-0 mb-4">
                Found <strong>{extractedDoors.length}</strong> doors. Please review and sanitize the SKUs below before restoring to ensure no mangled data.
              </p>

              <div className="flex-1 overflow-y-auto border border-gray-200 rounded-xl p-4 space-y-3 bg-gray-50/50">
                {extractedDoors.map((door, index) => (
                  <div key={index} className="flex items-center space-x-4 p-3 bg-white rounded-lg border border-gray-100 shadow-sm">
                    <img 
                      src={URL.createObjectURL(door.blob)} 
                      alt="Door" 
                      className="w-16 h-16 object-contain bg-gray-50 rounded border border-gray-200" 
                    />
                    <div className="flex-1">
                      <label className="block text-xs font-medium text-gray-700 mb-1">SKU</label>
                      <input 
                        type="text" 
                        value={door.sku} 
                        onChange={(e) => {
                          const newDoors = [...extractedDoors];
                          newDoors[index].sku = e.target.value;
                          setExtractedDoors(newDoors);
                        }}
                        className="w-full px-3 py-1.5 text-sm border border-gray-300 rounded-md focus:ring-indigo-500 focus:border-indigo-500"
                      />
                    </div>
                    <div className="w-40">
                      <label className="block text-xs font-medium text-gray-700 mb-1">Color</label>
                      <select 
                        value={door.color}
                        onChange={(e) => {
                          const newDoors = [...extractedDoors];
                          newDoors[index].color = e.target.value;
                          setExtractedDoors(newDoors);
                        }}
                        className="w-full px-3 py-1.5 text-sm border border-gray-300 rounded-md focus:ring-indigo-500 focus:border-indigo-500 capitalize"
                      >
                        <option value="white">White</option>
                        <option value="charcoal">Bronze</option>
                      </select>
                    </div>
                    <button 
                      onClick={() => {
                        const newDoors = [...extractedDoors];
                        newDoors.splice(index, 1);
                        setExtractedDoors(newDoors);
                      }}
                      className="p-2 text-gray-400 hover:text-red-600 hover:bg-red-50 rounded-lg transition-colors mt-5"
                      title="Remove Door"
                    >
                      <Trash2 className="w-5 h-5" />
                    </button>
                  </div>
                ))}
              </div>

              <div className="flex justify-end space-x-3 pt-6 shrink-0">
                <button
                  onClick={onClose}
                  className="px-4 py-2 rounded-xl font-medium text-gray-700 bg-gray-100 hover:bg-gray-200 transition-colors"
                >
                  Cancel
                </button>
                <button
                  onClick={handleRestore}
                  className="px-6 py-2 rounded-xl font-medium text-white bg-indigo-600 hover:bg-indigo-700 transition-colors"
                >
                  Restore {extractedDoors.length} Doors to Queue
                </button>
              </div>
            </div>
          )}
        </div>
      </div>
    </div>
  );
};
